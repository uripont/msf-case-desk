import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { describe, expect, test } from 'vitest'

import {
  INTAKE_TEMPLATE,
  INVESTIGATION_TEMPLATE,
  type Template,
} from '@case-desk/domain'
import { fullContent } from '@case-desk/domain/testing/fixtures'
import { PANEL_TEMPLATE } from '@case-desk/domain/testing/templates'

// NOTE: The expected stored content of a report that fills every item of a
// template (stage 4e). The JSON files are what the browser check sends and
// compares with what the server stores. They are generated by `fullContent`;
// `UPDATE_FIXTURES=1 pnpm --filter @case-desk/api test` rewrites them.

const FIXTURES = join(import.meta.dirname, '../../../packages/e2e/fixtures')

const TEMPLATES: ReadonlyArray<readonly [string, Template]> = [
  ['intake', INTAKE_TEMPLATE],
  ['investigation', INVESTIGATION_TEMPLATE],
  ['panel', PANEL_TEMPLATE],
]

describe.each(TEMPLATES)('the stored fixture of %s', (name, template) => {
  test('it is the file the browser check uses', () => {
    const file = join(FIXTURES, `${name}.content.json`)
    const expected = `${JSON.stringify(fullContent(template), null, 2)}\n`
    if (process.env.UPDATE_FIXTURES === '1') {
      mkdirSync(dirname(file), { recursive: true })
      writeFileSync(file, expected)
    }
    expect(readFileSync(file, 'utf8')).toBe(expected)
  })
})
